## The M.A.T.C.H Framework - Price Match Training

## Module Overview
Price match enquiries are a normal and valuable part of both our in-store and online customer interactions.

This module is designed to help you:
- Better understand why customers ask for price matches
- Approach these conversations with confidence
- Shift your mindset from pressure to opportunity
- Use a clear, consistent framework to guide the interaction

This training works alongside the M.A.T.C.H video, which introduces the overall mindset and conversation flow. Here, we focus on how to apply it in real customer scenarios.

## The M.A.T.C.H Framework
The M.A.T.C.H framework is your guide to handling these conversations effectively — whether in-store or over the phone.

## M - Make Them Feel Heard
Start by acknowledging the request and showing you''re on their side. Customers want to feel understood, not challenged.

Focus on:
- Empathy
- Active listening
- Exploring their needs

What this looks like:
- Recognising they want the best value
- Asking what they''re using the product for
- Checking if they need anything else

This helps:
- Build trust
- Reduce tension
- Open the conversation

## A - Assess the Situation
This is where you slow things down and take control. Avoid rushing straight to price. Instead:
- Ask open-ended questions
- Confirm the product is right for them
- Verify competitor and pricing details

Key focus:
- Is it the same product?
- Is it in stock?
- Is it legitimate (not grey stock)?
- Are there additional costs involved?

Slowing the conversation down positions you as the expert, not just the seller.

## T - Tell the Difference
Once you understand the situation, shift the focus from price to value. Help the customer see what they get when they buy from us:
- Strong stock availability — get it now, not later
- Total Care Plans — long-term peace of mind
- Ongoing after-sales support — real help when it matters

This step is critical. If value isn''t communicated, the customer can only compare price.

## C - Confirm Purchase Intent
Before moving forward with any pricing, confirm where the customer stands. This ensures:
- You''re working with a genuine buyer
- You''re not discounting unnecessarily
- The conversation is leading somewhere

Key focus:
- Are they ready to purchase?
- Will they proceed if the price is matched?
- Are there any concerns holding them back?

This step aligns both you and the customer toward the same outcome.

## H - Highlight Alternatives
Not every situation will result in a perfect price match, and that''s okay. What matters is offering a strong, confident solution. Your options:
- Price match where possible
- Offer the best available price
- Reinforce Ted''s value
- Suggest alternatives: second-hand options, bundle deals, or mixed solutions (new + used)

This keeps the conversation moving forward and increases your chance of closing the sale.

## Key Takeaways
- Price match enquiries are opportunities, not obstacles
- Customers are often closer to purchasing than you think
- Confidence and structure lead to better outcomes
- Value should always be communicated before price
- There is always a solution — your role is to find it'
