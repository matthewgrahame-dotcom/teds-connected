## Module Overview
Great coaching starts with great observation.

Many leaders feel confident giving feedback — but less confident deciding what to coach in the moment. In a busy retail environment, trying to observe everything leads to unclear feedback and missed opportunities.

This module introduces a structured way to observe specific, coachable behaviours during live customer interactions, without disrupting trade.

## Section 1: Observation Is the Foundation of Coaching
Coaching without clear observation leads to:
- Vague feedback ("Just be more confident")
- Assumptions ("They didn''t seem engaged")
- Over-coaching ("Here''s everything you could''ve done better")

Effective coaching requires evidence — not interpretation. You can only coach what you can clearly describe.

The FOCUS framework gives leaders a shared language to describe behaviours consistently across all stores.

## Section 2: Coaching Through the FOCUS Framework
FOCUS is not just a sales process — it''s a coaching structure. Each step represents a set of observable behaviours, not personality traits or sales results.

## F – First Impressions
**What Leaders Observe:**
- Speed of acknowledgement (within ~30 seconds)
- Eye contact and body language
- Whether the team member pauses other tasks
- Tone and warmth of greeting
- Store readiness supporting the interaction

**Coachable Behaviours:**
- Acknowledging customers immediately
- Using open, welcoming posture
- Maintaining awareness of the floor

**What NOT to Coach:**
- "They seemed awkward"
- "That customer didn''t look impressed"

## O – Open Conversations
**What Leaders Observe:**
- Use of open-ended questions
- Willingness to let the customer talk
- Listening cues (nodding, paraphrasing)
- Avoidance of yes/no questions

**Coachable Behaviours:**
- Asking curiosity-led questions
- Reflecting back understanding
- Showing interest without rushing

**What NOT to Coach:**
- "You should be more curious"
- "They didn''t seem engaged"

## C – Customised Solutions
**What Leaders Observe:**
- Clear link between stated needs and recommendations
- Use of benefit-led explanations
- Limiting choice instead of overwhelming
- Hands-on demonstrations

**Coachable Behaviours:**
- Repeating customer pain points
- Translating features into real-world value
- Using demos effectively

**What NOT to Coach:**
- "That wasn''t the right product"
- "You should''ve sold them something else"

## U – Upsell with Value
**What Leaders Observe:**
- Timing of add-on suggestions
- Relevance to stated needs
- Educational tone, not pressure
- Introduction of Care Plans early

**Coachable Behaviours:**
- Framing add-ons as solutions
- Linking accessories to use cases
- Positioning Care Plans as protection

**What NOT to Coach:**
- "You forgot to upsell"
- "That sale was too small"

## S – Secure Satisfaction
**What Leaders Observe:**
- Confidence when asking for the sale
- Clear closing language
- Reassurance after commitment
- Invitation back into the Ted''s ecosystem

**Coachable Behaviours:**
- Choosing the right close
- Reinforcing purchase decisions
- Highlighting ongoing support

**What NOT to Coach:**
- "They didn''t buy enough"
- "You should''ve pushed harder"

## Section 3: One Interaction = One Coaching Focus
Trying to coach multiple FOCUS steps in a single moment:
- Confuses the team member
- Dilutes the message
- Reduces behaviour change

**Coaching Rule: One interaction → One FOCUS behaviour**
Even if you observe multiple opportunities, choose:
- The most impactful
- The most repeatable
- The easiest to apply immediately

This keeps coaching clear, achievable, and effective.

## Section 4: Avoiding Assumptions When Observing
Common trap: "That customer wasn''t interested."
Better coaching observation: "The team member asked three closed questions in a row."

Assumptions are emotional. Behaviours are factual.

**If you can''t describe it without emotion, you can''t coach it well.**

## Section 5: Preparing for Coaching Moments
Before approaching a team member, mentally check:
1. What did I actually see or hear?
2. Which FOCUS stage does this relate to?
3. Is this a reinforce or a refine moment?

If you can answer those three questions, you''re ready to coach — quickly and confidently.

